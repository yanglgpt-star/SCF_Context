/** 用例自检：面积算出来跟标注的对不对得上。标注错会让「成功率」这个数没意义。 */
export function checkContours(tolerance = 0.02) {
  const bad = []
  for (const c of CONTOURS) {
    const actual = polygonArea(c.poly)
    if (Math.abs(actual - c.area) > tolerance) {
      bad.push({ id: c.id, declared: c.area, actual: Number(actual.toFixed(3)) })
    }
  }
  return bad
}
