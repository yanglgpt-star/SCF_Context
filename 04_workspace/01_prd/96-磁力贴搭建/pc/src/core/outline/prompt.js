/**
 * 提示词。两个调用各一份：文生图（出草稿图）和视觉理解（从草稿图里抠轮廓）。
 *
 * **`PROMPT_VERSION` 会写进 work.json**。提示词改了但版本号没改，会导致
 * 「同一份作品记录，两次重跑出来的轮廓不一样，却看不出为什么」—— 版本号就是
 * 那个「为什么」的答案。
 */
import { AGE_BANDS } from '../config.js'

export const PROMPT_VERSION = 'm4.1'

/**
 * 视觉理解用的方格边长。**必须与画布一致**。
 *
 * 因为 `solveContour` 的 `resolveCanvas` 只按轮廓包围盒定画布尺寸、**不缩放轮廓**
 * （solve.js:475）。让 AI 在一个 16×16 的格子里给轮廓、我们再缩到 12×10，缩放
 * 会把已经落在格点上的顶点推到半格上；而先缩后吸又会让「一格宽的特征」被四舍五入
 * 吃掉。所以格子数从一开始就对齐画布，全程不缩放。
 */
export const VISION_MARGIN = 1

const BAND_BY_KEY = Object.fromEntries(AGE_BANDS.map((b) => [b.key, b]))

/**
 * 文生图提示词。
 *
 * 全部笔墨都花在「画出一个能抠出轮廓的东西」上 —— 这一版不追求插画好看，
 * 因为下游是求解器：带渐变、带投影、带背景场景的图，抠出来的轮廓一定是碎的。
 * 真正值钱的三条约束是「单一主体」「纯色剪影」「直线几何边」。
 */
export function buildImagePrompt({ topic, band, cols, rows }) {
  const b = BAND_BY_KEY[band] ?? AGE_BANDS[0]
  const cells = cols * rows

  return [
    `画一个儿童磁力片拼搭用的平面图案：${topic}。`,
    '',
    '构图要求：',
    `- 正视图、完全平铺，不要透视、不要立体感、不要阴影、不要高光、不要渐变`,
    `- 主体只有一个，居中，占据画面约八成，四周留白`,
    `- 主体轮廓内部是纯色平涂，可以用几种色块分区，但不要纹理、不要描边、不要内部线条`,
    `- 轮廓本身要"几何化"：边只有水平、竖直和 45 度斜线三种，拐角是直角`,
    '- 不要圆弧、不要曲线、不要毛发/鳞片/羽毛这类碎细节、不要背景场景',
    '- 纯白或纯浅色背景，主体与背景对比强烈、边界干净',
    '',
    '复杂度要求：',
    `- 轮廓的复杂度大约相当于 ${b.minPieces} 到 ${b.maxPieces} 块磁力片拼出来的样子（${b.label}）`,
    `- 轮廓要连成一片，不要有和主体分开的小碎块，也不要镂空`,
    `- 整体宽高比接近 ${cols}:${rows}，主体在 ${cols}×${rows} 的格子里能完整放下（约 ${cells} 格）`,
  ].join('\n')
}

/**
 * 视觉理解提示词：从草稿图里抠出轮廓，**同时**要多边形和掩码两套表示。
 *
 * 两套都要，是因为它们擅长的地方不同：多边形能表达 45° 斜边（房子屋顶、菱形），
 * 但依赖 AI 数坐标的精度；掩码最稳，但斜边会变成台阶。一次调用里拿两套，
 * 让 `outline/extract.js` 去挑 —— 比先要一套、失败了再问一遍省一个来回。
 */
export function buildVisionPrompt({ cols, rows }) {
  const innerC = cols - VISION_MARGIN * 2
  const innerR = rows - VISION_MARGIN * 2

  return [
    '这是一张儿童磁力片拼搭用的图案。请把它"翻译"成一个可以用正方形、等腰直角三角形、',
    '长方形三种磁性贴片拼出来的形状，用两种方式描述同一个形状。',
    '',
    `坐标系：把整张图放进一个 ${cols} 列 × ${rows} 行的方格网里，左上角是 (0, 0)，`,
    'x 向右、y 向下。**1 个单位 = 1 个格子**。',
    `形状请控制在 ${VISION_MARGIN} 到 ${cols - VISION_MARGIN} 之间（纵向 ${VISION_MARGIN} 到 ${rows - VISION_MARGIN}），`,
    `也就是 ${innerC} × ${innerR} 格以内，不要顶到边。`,
    '',
    '两种表示：',
    `1. "polygon"：形状外轮廓的顶点数组，按顺序绕一圈（顺时针或逆时针都行），形如 [[0,0],[4,0],[4,3],[0,3]]。`,
    '   顶点坐标用格子数表示，可以是小数。**屋顶、斜边这类 45 度的地方请如实给斜线**，',
    '   不要为了凑整数把斜边拆成台阶。',
    `2. "mask"：同样形状的方格掩码，正好 ${rows} 行、每行正好 ${cols} 个字符，`,
    '   属于形状的格子写 "#"、不属于的写 "."。它和多边形描述的是同一个形状，',
    '   多边形里的斜边在掩码里就是台阶。',
    '',
    '形状规则：',
    '- 只有水平、竖直、45 度和 135 度四种边 —— 不要其他角度',
    '- 连成一片，不要有零散的小块，不要镂空',
    '- 忽略图案内部的颜色分区和纹理，只要最外面那一圈轮廓',
    '',
    '只输出一个 JSON 对象，不要任何解释文字，格式：',
    '{"polygon": [[0,0],[4,0],[4,3],[0,3]], "mask": ["....", "..##", "..##"], "note": "一句话说明画的是什么"}',
  ].join('\n')
}
